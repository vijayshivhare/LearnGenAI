def excel_dict_to_text(sheet_dict: dict) -> str:
    """
    Converts a dictionary of DataFrames (from an Excel file with multiple sheets)
    into a readable text summary for LLM consumption.

    Args:
        sheet_dict (dict): Keys are sheet names, values are pandas DataFrames.
        max_rows_per_sheet (int): Number of rows to show per sheet.

    Returns:
        str: A formatted string representing the sheets, their columns, types, and sample data.
    """

    summary_lines = []

    for sheet_name, df in sheet_dict.items():
        summary_lines.append(f"\n=== Sheet: {sheet_name} ===")

        if df.empty:
            summary_lines.append("⚠️ Sheet is empty.\n")
            continue

        # Columns and data types
        col_info = ", ".join([f"{col} ({dtype})" for col, dtype in df.dtypes.items()])
        summary_lines.append(f"Columns: {col_info}")

        # Sample rows
        sample_text = df.to_markdown(index=False)
        summary_lines.append(f"Sample rows:\n{sample_text}")

    return "\n\n".join(summary_lines)


